def unique_example_path(path: Path) -> Path:
    candidate = path.with_name(f"{path.name}.example")
    if not candidate.exists():
        return candidate

    index = 2
    while True:
        numbered = path.with_name(f"{path.name}.example{index}")
        if not numbered.exists():
            return numbered
        index += 1


def write_text_file(path: Path, text: str, overwrite: bool = False) -> Path:
    destination = path
    if destination.exists() and not overwrite:
        destination = unique_example_path(destination)
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text(text, encoding="utf-8")
    return destination


def init_guardrail_docs(root: Path, overwrite: bool = False) -> list[Path]:
    written: list[Path] = []
    for relative_path, text in TEMPLATES.items():
        written.append(write_text_file(root / relative_path, text, overwrite))
    return written
